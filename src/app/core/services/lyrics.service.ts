import { Service, inject } from '@angular/core';
import { HttpClient, HttpParams } from '@angular/common/http';
import { Observable, catchError, of } from 'rxjs';
import { apiUrl } from '../config/api.config';

export interface LrclibResponse {
  id: number;
  name: string;
  trackName: string;
  artistName: string;
  albumName: string;
  duration: number;
  instrumental: boolean;
  plainLyrics: string;
  syncedLyrics: string | null;
}

export interface ParsedLyricLine {
  time: number; // in seconds
  text: string;
}

export interface CleanTrackInfo {
  trackName: string;
  artistName: string;
}

/**
 * Cleans YouTube video titles and channel names to improve search matches in lyrics databases (Lrclib).
 * Strips YouTube-specific noise like "(Official Music Video)", "[Official Audio]", "(feat. ...)",
 * " - Topic" channel suffixes, and extracts "Artist - Title" when embedded in video titles.
 */
export function cleanLyricsSearchQuery(
  rawTrackName: string,
  rawArtistName: string = '',
): CleanTrackInfo {
  let title = (rawTrackName || '').trim();
  let artist = (rawArtistName || '').trim();

  // Strip " - Topic" generated by YouTube Music automated artist channels
  artist = artist.replace(/\s*-\s*Topic$/i, '').trim();

  // If title has "Artist - Title" format and artist is either missing or just Topic
  if (title.includes(' - ') && (!artist || rawArtistName.toLowerCase().includes('topic'))) {
    const parts = title.split(' - ');
    if (parts.length >= 2) {
      if (!artist) {
        artist = parts[0].trim();
      }
      title = parts.slice(1).join(' - ').trim();
    }
  }

  // Remove common YouTube bracketed tags / video noise
  title = title
    .replace(
      /[\(\[](?:official\s+(?:music\s+)?video|official\s+audio|official\s+lyric\s+video|official\s+visualizer|video\s+oficial|audio\s+oficial|video\s+con\s+letra|video\s+lírico|lyric\s+video|visualizer|remastered(?:\s+\d+)?|remaster|4k|hd|audio)[\)\]]/gi,
      '',
    )
    // Remove (feat. ...) or [feat. ...] or (ft. ...)
    .replace(/[\(\[](?:feat|ft)\.?\s+[^\)\]]+[\)\]]/gi, '')
    // Remove trailing/leading dashes, colons or excess spaces
    .replace(/^[\s\-–—:]+|[\s\-–—:]+$/g, '')
    .replace(/\s+/g, ' ')
    .trim();

  return {
    trackName: title || rawTrackName.trim(),
    artistName: artist || rawArtistName.trim(),
  };
}

@Service()
export class LyricsService {
  private readonly _http = inject(HttpClient);

  /**
   * Fetches lyrics for a track from the backend.
   */
  public getLyrics(
    trackName: string,
    artistName: string,
    duration?: number,
  ): Observable<LrclibResponse | null> {
    const cleaned = cleanLyricsSearchQuery(trackName, artistName);
    let params = new HttpParams()
      .set('track_name', cleaned.trackName)
      .set('artist_name', cleaned.artistName);

    if (duration && duration > 0) {
      params = params.set('duration', Math.round(duration).toString());
    }

    return this._http.get<LrclibResponse>(apiUrl('youtube', 'lyrics'), { params }).pipe(
      catchError(() => {
        return of(null);
      }),
    );
  }

  /**
   * Parses an LRC format string (syncedLyrics) into an array of lines with seconds.
   *
   * Una misma línea puede llevar varios time tags (`[00:01.00][01:00.00] coro`), y
   * las cabeceras de metadatos (`[ar:]`, `[ti:]`, `[length:]`) no son letra: se ignoran.
   * Si el archivo contiene una cabecera `[offset: +/-ms]`, se aplica a todas las marcas.
   */
  public parseSyncedLyrics(lrc: string): ParsedLyricLine[] {
    if (!lrc) return [];

    let fileOffsetSeconds = 0;
    const offsetMatch = lrc.match(/\[offset:\s*([+-]?\d+)\]/i);
    if (offsetMatch) {
      const ms = parseInt(offsetMatch[1], 10);
      if (!isNaN(ms)) {
        fileOffsetSeconds = ms / 1000;
      }
    }

    // \d+ para que una pista de más de 99 minutos no quede sin parsear.
    const timeRegex = /\[(\d+):(\d{1,2}(?:[.:]\d+)?)\]/g;
    const result: ParsedLyricLine[] = [];

    for (const line of lrc.split('\n')) {
      const times: number[] = [];
      for (const match of line.matchAll(timeRegex)) {
        const minutes = parseInt(match[1], 10);
        const seconds = parseFloat(match[2].replace(':', '.'));
        const calculatedTime = Math.max(0, minutes * 60 + seconds + fileOffsetSeconds);
        times.push(Math.round(calculatedTime * 1000) / 1000);
      }

      if (times.length === 0) {
        continue; // Cabeceras de metadatos o líneas sin sincronizar.
      }

      // La letra es lo que queda tras quitar todos los time tags de la línea:
      // en `[00:10.00][01:00.00] Chorus` el texto es `Chorus`, no el concatenado.
      const cleanText = line.replace(timeRegex, '').trim();
      for (const time of times) {
        result.push({ time, text: cleanText });
      }
    }

    return result.sort((a, b) => a.time - b.time);
  }
}

